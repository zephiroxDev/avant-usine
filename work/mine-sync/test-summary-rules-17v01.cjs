const assert=require('node:assert/strict');
const rules=require('../github-sync-import/summary-rules-17v01.js');
assert.equal(rules.annualPeriod(2026).revealAt,'2026-12-31T23:00:00.000Z');
assert.equal(rules.revealed(2026,'2026-12-31T22:59:59.999Z'),false);
assert.equal(rules.revealed(2026,'2026-12-31T23:00:00.000Z'),true);
assert.equal(rules.parisMidnight(2027,7,1),'2027-06-30T22:00:00.000Z');
assert.equal(rules.publicEditionAllowed(2026),false);
assert.equal(rules.publicEditionAllowed(2027),true);
assert.equal(rules.trophyMayBeExhibited({year:2026,earned:true},'2028-01-01'),false);
assert.equal(rules.trophyMayBeExhibited({year:2027,earned:true},'2028-01-01'),true);
assert.equal(rules.addCalendarMonths('2027-08-31',6),'2028-02-29');
assert.doesNotThrow(()=>rules.programmedPeriod('2027-01-01','2027-07-01','2027-07-01'));
assert.throws(()=>rules.programmedPeriod('2027-01-01','2027-07-02','2027-07-02'));
assert.throws(()=>rules.programmedPeriod('2027-02-30','2027-03-01','2027-03-02'));
assert.throws(()=>rules.programmedPeriod('2027-01-01','2027-07-01','2027-06-30'));
assert.equal(rules.listeningTrophies(3000*3600,2026,'2026-12-31T22:59:59Z').filter(t=>t.earned).length,0);
assert.equal(rules.listeningTrophies(3000*3600,2026,'2027-01-01').filter(t=>t.earned).length,12);
assert.equal(rules.listeningTrophies(2999*3600,2026,'2027-01-01').at(-1).earned,false);
const base={ownerId:'owner',viewerId:'creator',summaryId:'annual-2026'};
assert.equal(rules.mayReadSummary(base),false);
assert.equal(rules.mayReadSummary({...base,viewerId:'owner'}),true);
const grant={ownerId:'owner',viewerId:'creator',summaryId:'annual-2026',accepted:true};
